param([Parameter(Mandatory = $true)][string]$OutputPath)
$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.Drawing
$bitmap = [System.Drawing.Bitmap]::new(64, 64)
$graphics = [System.Drawing.Graphics]::FromImage($bitmap)
$graphics.SmoothingMode = [System.Drawing.Drawing2D.SmoothingMode]::AntiAlias
$graphics.Clear([System.Drawing.Color]::Transparent)
$background = [System.Drawing.SolidBrush]::new([System.Drawing.Color]::FromArgb(29, 43, 55))
$rounded = [System.Drawing.Drawing2D.GraphicsPath]::new()
$rounded.AddArc(0, 0, 26, 26, 180, 90)
$rounded.AddArc(38, 0, 26, 26, 270, 90)
$rounded.AddArc(38, 38, 26, 26, 0, 90)
$rounded.AddArc(0, 38, 26, 26, 90, 90)
$rounded.CloseFigure()
$graphics.FillPath($background, $rounded)
$pen = [System.Drawing.Pen]::new([System.Drawing.Color]::White, 3)
$pen.LineJoin = [System.Drawing.Drawing2D.LineJoin]::Round
$graphics.DrawRectangle($pen, 11, 24, 20, 16)
$graphics.DrawLine($pen, 31, 32, 35, 32)
$points = [System.Drawing.PointF[]]@(
    [System.Drawing.PointF]::new(47, 20),
    [System.Drawing.PointF]::new(59, 32),
    [System.Drawing.PointF]::new(47, 44),
    [System.Drawing.PointF]::new(35, 32)
)
$graphics.DrawPolygon($pen, $points)
$stream = [System.IO.MemoryStream]::new()
$bitmap.Save($stream, [System.Drawing.Imaging.ImageFormat]::Png)
$png = $stream.ToArray()
$file = [System.IO.File]::Create($OutputPath)
$writer = [System.IO.BinaryWriter]::new($file)
$writer.Write([uint16]0)
$writer.Write([uint16]1)
$writer.Write([uint16]1)
$writer.Write([byte]64)
$writer.Write([byte]64)
$writer.Write([byte]0)
$writer.Write([byte]0)
$writer.Write([uint16]1)
$writer.Write([uint16]32)
$writer.Write([uint32]$png.Length)
$writer.Write([uint32]22)
$writer.Write($png)
$writer.Dispose()
$stream.Dispose()
$pen.Dispose()
$rounded.Dispose()
$background.Dispose()
$graphics.Dispose()
$bitmap.Dispose()
